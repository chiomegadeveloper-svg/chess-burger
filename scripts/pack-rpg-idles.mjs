// Normalize generated idle silhouettes to the same 200px extent and foot baseline as attack poses.
import sharp from 'sharp';
import {mkdir,writeFile} from 'node:fs/promises';
const groups=[['rogue','theft','assassin','mage','tank','archer','queen','crusader'],['chaanack','erpack','donkuber','windee','kalaagg','pektu','mhakiduk','odeksa','buhokba','muraduk'],['punsuck','conchita','jengot','draguu','baluu','kassag']];
const inputs=process.argv.slice(2);if(inputs.length!==3)throw Error('Supply the transparent hero, monster and boss atlases.');
const out=new URL('../public/rpg/assets/idle/',import.meta.url);await mkdir(out,{recursive:true});const catalog={};
for(let g=0;g<3;g++){
 const {width,height}=await sharp(inputs[g]).metadata(),rows=groups[g].length/2;
 for(let i=0;i<groups[g].length;i++){
  const left=Math.round((i%2)*width/2),right=Math.round(((i%2)+1)*width/2),top=Math.round(Math.floor(i/2)*height/rows),bottom=Math.round((Math.floor(i/2)+1)*height/rows);
  const cell=await sharp(inputs[g]).extract({left,top,width:right-left,height:bottom-top}).png().toBuffer();
  const {data,info}=await sharp(cell).ensureAlpha().raw().toBuffer({resolveWithObject:true});let x0=info.width,y0=info.height,x1=-1,y1=-1;
  for(let y=0;y<info.height;y++)for(let x=0;x<info.width;x++)if(data[(y*info.width+x)*4+3]>32){x0=Math.min(x0,x);x1=Math.max(x1,x);y0=Math.min(y0,y);y1=Math.max(y1,y);}
  if(x1<x0)throw Error('Empty idle pose '+groups[g][i]);
  const w=x1-x0+1,h=y1-y0+1,scale=200/Math.max(w,h),rw=Math.round(w*scale),rh=Math.round(h*scale);
  const body=await sharp(cell).extract({left:x0,top:y0,width:w,height:h}).resize(rw,rh,{kernel:'nearest'}).png().toBuffer(),id=groups[g][i];
  await sharp({create:{width:512,height:512,channels:4,background:'#00000000'}}).composite([{input:body,left:Math.round((512-rw)/2),top:356-rh}]).webp({lossless:true}).toFile(new URL(id+'.webp',out).pathname);
  catalog[id]={src:`assets/idle/${id}.webp`,facing:g===0?'right':'left',tile:512,visible:200};
 }
}
await writeFile(new URL('../rpg/src/character-idles.js',import.meta.url),'// Generated by scripts/pack-rpg-idles.mjs.\nwindow.RPG_CHARACTER_IDLES='+JSON.stringify(catalog,null,1)+';\n');
console.log('Packed 24 tile-free breathing idle poses.');
