// Packs generated poses into isolated 512px cells; does not alter character artwork.
import sharp from 'sharp';
import {mkdir,writeFile} from 'node:fs/promises';
const groups=[['rogue','theft','assassin','mage','tank','archer','queen','crusader'],['chaanack','erpack','donkuber','windee','kalaagg','pektu','mhakiduk','odeksa','buhokba','muraduk'],['punsuck','conchita','jengot','draguu','baluu','kassag']];
const inputs=process.argv.slice(2);if(inputs.length!==3)throw Error('Supply hero, monster, boss source PNG paths.');
const directory=new URL('../public/rpg/assets/attacks/',import.meta.url);await mkdir(directory,{recursive:true});
const catalog={};
for(let g=0;g<3;g++){
 const {data,info}=await sharp(inputs[g]).ensureAlpha().raw().toBuffer({resolveWithObject:true});
 const gaps=[];let gapStart=-1;
 for(let y=0;y<info.height;y++){
  let ink=0;for(let x=0;x<info.width;x++)if(data[(y*info.width+x)*4+3]>32)ink++;
  if(ink<3&&gapStart<0)gapStart=y;
  if(ink>=3&&gapStart>=0){if(y-gapStart>2&&gapStart>0)gaps.push(Math.floor((gapStart+y)/2));gapStart=-1;}
 }
 const rows=groups[g].length;if(gaps.length!==rows-1)throw Error('Review source row boundaries before packing.');
 const boundaries=[0,...gaps,info.height];
 for(let row=0;row<rows;row++){
  const top=boundaries[row],height=boundaries[row+1]-top,width=info.width;
  const visited=new Uint8Array(width*height),queue=new Int32Array(width*height);
  const rawFrames=Array.from({length:4},()=>Buffer.alloc(width*height*4));
  for(let index=0;index<visited.length;index++){
   if(visited[index]||data[((top*width)+index)*4+3]<=32)continue;
   let head=0,tail=1,sumX=0;queue[0]=index;visited[index]=1;
   while(head<tail){const at=queue[head++],x=at%width,y=Math.floor(at/width);sumX+=x;
    for(let dy=-1;dy<=1;dy++)for(let dx=-1;dx<=1;dx++){
     const nx=x+dx,ny=y+dy,next=ny*width+nx;
     if(nx<0||nx>=width||ny<0||ny>=height||visited[next]||data[((top*width)+next)*4+3]<=32)continue;
     visited[next]=1;queue[tail++]=next;
    }
   }
   if(tail<20)continue;
   const col=Math.max(0,Math.min(3,Math.floor(sumX/tail/width*4))),raw=rawFrames[col];
   for(let n=0;n<tail;n++){const at=queue[n],offset=(top*width+at)*4;data.copy(raw,at*4,offset,offset+4);}
  }
  const crops=rawFrames.map(raw=>{
   let x0=width,y0=height,x1=0,y1=0;
   for(let y=0;y<height;y++)for(let x=0;x<width;x++)if(raw[(y*width+x)*4+3]){x0=Math.min(x0,x);x1=Math.max(x1,x);y0=Math.min(y0,y);y1=Math.max(y1,y);}
   if(x0>x1)throw Error('Empty character pose');
   return {raw,width,height,left:x0,top:y0,w:x1-x0+1,h:y1-y0+1};
  });
  const scale=200/Math.max(...crops.flatMap(c=>[c.w,c.h]));
  const layers=[];
  for(let col=0;col<4;col++){
   const c=crops[col],w=Math.max(1,Math.round(c.w*scale)),h=Math.max(1,Math.round(c.h*scale));
   const input=await sharp(c.raw,{raw:{width:c.width,height:c.height,channels:4}}).extract({left:c.left,top:c.top,width:c.w,height:c.h}).resize(w,h,{kernel:'nearest'}).png().toBuffer();
   layers.push({input,left:col*512+Math.round((512-w)/2),top:356-h});
  }
  const id=groups[g][row];await sharp({create:{width:2048,height:512,channels:4,background:'#00000000'}}).composite(layers).webp({lossless:true}).toFile(new URL(id+'.webp',directory).pathname);
  catalog[id]={src:`assets/attacks/${id}.webp`,frames:4,tile:512,visible:200,facing:g===0?'right':'left'};
 }
}
await writeFile(new URL('../rpg/src/character-attacks.js',import.meta.url),'// Generated by scripts/pack-rpg-character-attacks.mjs.\nwindow.RPG_CHARACTER_ATTACKS='+JSON.stringify(catalog,null,1)+';\n');
console.log('Packed 96 poses for 24 characters with at least 156px transparent padding per side.');
